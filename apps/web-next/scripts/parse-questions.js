const fs = require('fs');
const path = require('path');

const rootDir = path.join(__dirname, '..', '..', '..');
const systemMdPath = path.join(rootDir, 'system.md');
const outputPath = path.join(rootDir, 'apps', 'web-next', 'app', 'system-design', 'data', 'questions.ts');

if (!fs.existsSync(systemMdPath)) {
  console.error("system.md not found at:", systemMdPath);
  process.exit(1);
}

const fileContent = fs.readFileSync(systemMdPath, 'utf-8');
const lines = fileContent.split(/\r?\n/);

const sections = [];
const questions = [];

let currentSection = null;
let currentQuestion = null;
let parsingVideos = false;

const sectionRegex = /^##\s+(\d+)\.\s+(.*)$/;
const videoRegex = /^[-*]\s+\[(.*?)\]\((.*?)\)/;
const questionRegex = /^\*\*(\d+)\.\s*(.*?)\*\*/;

for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  const trimmed = line.trim();

  // Check for section
  const sectionMatch = line.match(sectionRegex);
  if (sectionMatch) {
    const id = parseInt(sectionMatch[1], 10);
    const name = sectionMatch[2].trim();
    currentSection = {
      id,
      name,
      videos: [],
      questionsCount: 0
    };
    sections.push(currentSection);
    currentQuestion = null;
    parsingVideos = false;
    continue;
  } else if (line.startsWith('## ') && sections.length > 0) {
    // Stop parsing once we hit Contributing, License, etc.
    break;
  }

  // Check for recommended videos heading
  if (trimmed === '**📺 Recommended videos for this section:**') {
    parsingVideos = true;
    continue;
  }

  // Parse videos if inside video block
  if (parsingVideos) {
    const videoMatch = trimmed.match(videoRegex);
    if (videoMatch) {
      currentSection.videos.push({
        name: videoMatch[1].trim(),
        url: videoMatch[2].trim()
      });
      continue;
    } else if (trimmed !== '' && !trimmed.startsWith('-') && !trimmed.startsWith('*')) {
      // Stopped parsing videos
      parsingVideos = false;
    }
  }

  // Check for question
  const questionMatch = line.match(questionRegex);
  if (questionMatch) {
    const id = parseInt(questionMatch[1], 10);
    const questionText = questionMatch[2].trim();
    
    currentQuestion = {
      id,
      number: id,
      sectionId: currentSection ? currentSection.id : 0,
      question: questionText,
      answerLines: []
    };
    questions.push(currentQuestion);
    if (currentSection) {
      currentSection.questionsCount++;
    }
    continue;
  }

  // Accumulate answer lines if parsing a question
  if (currentQuestion) {
    // If we hit horizontal rule, stop accumulating for the current question
    if (trimmed === '---') {
      currentQuestion = null;
      continue;
    }
    // Don't accumulate contributing or license section headers if they appear
    if (line.startsWith('## ')) {
      currentQuestion = null;
      continue;
    }
    
    currentQuestion.answerLines.push(line);
  }
}

// Post-process questions to clean up answers
const processedQuestions = questions.map(q => {
  let answer = q.answerLines.join('\n').trim();
  // Remove trailing horizontal rule or other separator lines if accumulated
  if (answer.endsWith('\n---')) {
    answer = answer.slice(0, -4).trim();
  }
  return {
    id: q.id,
    number: q.number,
    sectionId: q.sectionId,
    question: q.question,
    answer: answer
  };
});

// Output code file
const dir = path.dirname(outputPath);
if (!fs.existsSync(dir)){
    fs.mkdirSync(dir, { recursive: true });
}

const outputContent = `// Automatically generated by scripts/parse-questions.js
export interface VideoResource {
  name: string;
  url: string;
}

export interface Section {
  id: number;
  name: string;
  videos: VideoResource[];
  questionsCount: number;
}

export interface Question {
  id: number;
  number: number;
  sectionId: number;
  question: string;
  answer: string;
}

export const sections: Section[] = ${JSON.stringify(sections, null, 2)};

export const questions: Question[] = ${JSON.stringify(processedQuestions, null, 2)};
`;

fs.writeFileSync(outputPath, outputContent, 'utf-8');
console.log(`Successfully parsed ${sections.length} sections and ${processedQuestions.length} questions.`);
